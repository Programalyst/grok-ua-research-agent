import { useState } from "react";
import type {
  GameProfile,
  GameProfileUpdate,
  Language,
  SuggestionStatus,
} from "../api/types";
import {
  useGenerateProfile,
  useProfile,
  useSaveProfile,
} from "../hooks/queries";
import { ChipInput } from "./ChipInput";

const LANG_LABEL: Record<Language, string> = {
  en: "English",
  zh: "中文",
  ja: "日本語",
  ko: "한국어",
};

function toEditable(p: GameProfile): GameProfileUpdate {
  return {
    themes: [...p.themes],
    keywords_by_language: { ...p.keywords_by_language },
    suggested_comparables: p.suggested_comparables.map((c) => ({ ...c })),
    visual_style: [...p.visual_style],
    target_audience: p.target_audience,
  };
}

function Editor({ gameId, profile }: { gameId: string; profile: GameProfile }) {
  const save = useSaveProfile(gameId);
  const [draft, setDraft] = useState(() => toEditable(profile));
  const [dirty, setDirty] = useState(false);
  const set = <K extends keyof GameProfileUpdate>(
    k: K,
    v: GameProfileUpdate[K],
  ) => {
    setDraft((d) => ({ ...d, [k]: v }));
    setDirty(true);
  };
  const setStatus = (i: number, status: SuggestionStatus) =>
    set(
      "suggested_comparables",
      draft.suggested_comparables.map((c, j) =>
        j === i ? { ...c, status } : c,
      ),
    );

  return (
    <div className="profile">
      <p className="muted">
        Generated by <b>{profile.model || profile.generated_by}</b>
        {profile.cost_usd != null && profile.cost_usd > 0 && (
          <>
            {" "}
            · $
            {profile.cost_usd < 0.01
              ? profile.cost_usd.toFixed(4)
              : profile.cost_usd.toFixed(3)}
          </>
        )}
        {profile.edited && " · edited"} ·{" "}
        {new Date(profile.updated_at).toLocaleString()}
      </p>

      <div className="field">
        <span>Themes</span>
        <ChipInput
          value={draft.themes}
          onChange={(v) => set("themes", v)}
          max={30}
        />
      </div>

      <div className="field">
        <span>Player-language keywords</span>
        {(Object.keys(draft.keywords_by_language) as Language[]).map((lang) => (
          <div key={lang} className="kw-row">
            <b>{LANG_LABEL[lang] ?? lang}</b>
            <ChipInput
              value={draft.keywords_by_language[lang] ?? []}
              onChange={(v) =>
                set("keywords_by_language", {
                  ...draft.keywords_by_language,
                  [lang]: v,
                })
              }
              max={50}
            />
          </div>
        ))}
      </div>

      <div className="field">
        <span>Suggested comparable games</span>
        <ul className="suggestions">
          {draft.suggested_comparables.map((c, i) => (
            <li key={c.name} className={c.status}>
              <div>
                <b>{c.name}</b>{" "}
                <span className={`badge ${c.status}`}>{c.status}</span>
                <div className="muted">{c.reason}</div>
              </div>
              <div className="row">
                <button
                  type="button"
                  disabled={c.status === "accepted"}
                  onClick={() => setStatus(i, "accepted")}
                >
                  Accept
                </button>
                <button
                  type="button"
                  disabled={c.status === "rejected"}
                  onClick={() => setStatus(i, "rejected")}
                >
                  Reject
                </button>
              </div>
            </li>
          ))}
        </ul>
      </div>

      <div className="field">
        <span>Visual style</span>
        <ChipInput
          value={draft.visual_style}
          onChange={(v) => set("visual_style", v)}
          max={30}
        />
      </div>

      <label>
        Target audience
        <textarea
          rows={3}
          value={draft.target_audience}
          onChange={(e) => set("target_audience", e.target.value)}
        />
      </label>

      <div className="row">
        <button
          type="button"
          className="primary"
          disabled={!dirty || save.isPending}
          onClick={() =>
            save.mutate(draft, { onSuccess: () => setDirty(false) })
          }
        >
          {save.isPending ? "Saving…" : dirty ? "Save profile" : "Saved"}
        </button>
        {save.error && <span className="error">{save.error.message}</span>}
      </div>
    </div>
  );
}

export function ProfilePanel({ gameId }: { gameId: string }) {
  const profile = useProfile(gameId);
  const generate = useGenerateProfile(gameId);
  const confirmRegenerate = () =>
    !profile.data?.edited ||
    window.confirm("Regenerating will overwrite your edits. Continue?");

  return (
    <section className="card">
      <div className="row spread">
        <h2>Game profile</h2>
        <button
          type="button"
          className="primary"
          disabled={generate.isPending}
          onClick={() => confirmRegenerate() && generate.mutate()}
        >
          {generate.isPending
            ? "Generating…"
            : profile.data
              ? "Regenerate profile"
              : "Generate profile"}
        </button>
      </div>
      {generate.error && <p className="error">{generate.error.message}</p>}
      {profile.isLoading && <p>Loading…</p>}
      {profile.data === null && (
        <p className="muted">No profile yet. Generate one from your brief.</p>
      )}
      {profile.data && (
        <Editor
          key={profile.data.updated_at}
          gameId={gameId}
          profile={profile.data}
        />
      )}
    </section>
  );
}
